"""Merge a candidate OSD face onto the Betaflight default font_data[].

The FC1 board renders ONE font — `font_data[]` (12x18 2bpp). Its lowercase
code points (0x61-0x7A) hold Betaflight OSD symbol glyphs that MSP overlays
rely on, so we never overwrite them. This tool takes the original BF font as a
base and overlays ASCII letters/digits/punctuation from a candidate face, EXCEPT:

  * GLOBAL_KEEP  — code points kept as the BF default in every face (the custom
    '$' = "MAX" glyph; plus glyphs that auto-render poorly at 12x18 and where the
    BF default is clean & symmetric: % # & ? ; ( ) [ ] + * < > Q).
  * OVERRIDES    — hand-authored glyphs (see glyph_overrides.py) for faces where
    even a good face render is wrong, e.g. Terminus 'G'.

Outputs one `font_data_<face>.c` per face; CMake's OSD_FONT selects which one
compiles. The `default` face (no overlay) is byte-identical to the original
font_bf_default.h.

Example:
  .venv/bin/python python/merge_font.py \\
      --base src/fonts/font_bf_default.h \\
      --candidate python/candidates/plexmono.bin \\
      --face plexmono --out src/fonts/font_data_plexmono.c
"""

import argparse
import importlib.util
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent

STRIDE = 64
COUNT = 256

# Code points kept as the BF default in EVERY face (never overlaid).
# Only the custom '$' = "MAX" indicator — it's a special symbol, not a typeface
# glyph. Everything else is rendered natively from each face so a font is one
# consistent style (no BF-styled punctuation grafted onto face-styled letters).
GLOBAL_KEEP = {0x24}

# ---- import the generator (for pack_glyph + px_t constants) ----
_spec = importlib.util.spec_from_file_location("_gen", HERE / "make_pixel_font_2bpp.py")
_gen = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_gen)

HEADER = """/* SPDX-License-Identifier: GPL-2.0-only */
/* Auto-generated by python/merge_font.py — face: {face}.
 * 12x18 2bpp, 256 glyphs, {stride}-byte stride, section(".font").
 * Base: {base}; ASCII letters/digits overlaid from {cand};
 * GLOBAL_KEEP code points + Betaflight symbols (0x61-0x7A) preserved;
 * editable overrides applied (see python/overrides/<face>_0xHEX.txt). Do not edit. */
#include <stdint.h>
#include "font_data.h"

__attribute__((section(".font")))
const uint8_t font_data[16384] = {{
"""


def strip_comments(text):
    return re.sub(r"/\*.*?\*/", "", text, flags=re.DOTALL)


def parse_base(path):
    """Extract the 16384 font_data bytes from the original font_bf_default.h."""
    text = strip_comments(path.read_text(encoding="utf-8"))
    body = text.split("=", 1)[1] if "=" in text else text
    nums = [int(t, 16) for t in re.findall(r"0x([0-9A-Fa-f]+)", body)]
    if len(nums) != COUNT * STRIDE:
        nums = nums[-COUNT * STRIDE:]
    if len(nums) != COUNT * STRIDE:
        sys.exit(f"error: parsed {len(nums)} bytes from {path}, expected {COUNT*STRIDE}")
    return bytearray(nums)


def overlay_set(extra_keep):
    """Code points to overwrite with the candidate face."""
    return {c for c in range(0x20, 0x7F)
            if not (0x61 <= c <= 0x7A)
            and c not in GLOBAL_KEEP
            and c not in extra_keep}


# ---- Editable glyph overrides (text files) -----------------------------------
# python/overrides/<face>_0xHEX.txt  ->  18 lines x 12 chars, packed VERBATIM
# (no auto-outline; the file IS the final glyph). Legend:  . transparent  # white  K black
OVERRIDES_DIR = HERE / "overrides"


def parse_glyph_text(text):
    """Parse an override text file into an 18x12 px_t grid (K/#/.)."""
    rows = [ln for ln in text.splitlines() if ln.strip() and not ln.lstrip().startswith("#")]
    grid = []
    for ln in rows[:18]:
        ln = (ln[:12]).ljust(12, ".")
        grid.append([_gen.PX_BLACK if c.upper() == "K"
                     else _gen.PX_WHITE if c == "#"
                     else _gen.PX_TRANSPARENT for c in ln])
    while len(grid) < 18:
        grid.append([_gen.PX_TRANSPARENT] * 12)
    return grid


def load_text_overrides(face):
    """{code: grid} for every python/overrides/<face>_0xHEX.txt present."""
    overrides = {}
    if not OVERRIDES_DIR.is_dir():
        return overrides
    pat = re.compile(rf"^{re.escape(face)}_(0x[0-9A-Fa-f]+)\.txt$")
    for p in sorted(OVERRIDES_DIR.glob(f"{face}_*.txt")):
        m = pat.match(p.name)
        if m:
            overrides[int(m.group(1), 16)] = parse_glyph_text(p.read_text(encoding="utf-8"))
    return overrides


def override_to_bytes(grid):
    return _gen.pack_glyph(grid)


def write_c(path, face, base_name, cand_name, data):
    lines = [HEADER.format(face=face, base=base_name, cand=cand_name, stride=STRIDE)]
    per_line = 16
    for code in range(COUNT):
        lines.append(f"/* Hex 0x{code:02X} */")
        g = data[code * STRIDE:(code + 1) * STRIDE]
        for i in range(0, STRIDE, per_line):
            chunk = g[i:i + per_line]
            last = (code == COUNT - 1) and (i + per_line >= STRIDE)
            sep = "" if last else ","
            lines.append("    " + ", ".join(f"0x{b:02X}" for b in chunk) + sep)
    lines.append("};")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def parse_codes(spec):
    """Parse '0x24,0x25,...' (or '36,37') into a set of ints."""
    out = set()
    for tok in spec.split(","):
        tok = tok.strip()
        if not tok:
            continue
        out.add(int(tok, 16) if tok.lower().startswith("0x") else int(tok, 10))
    return out


def main():
    ap = argparse.ArgumentParser(description="Merge a candidate face onto font_data[]")
    ap.add_argument("--base", required=True, help="original font_bf_default.h")
    ap.add_argument("--candidate", required=True, help="face .bin from make_pixel_font_2bpp.py")
    ap.add_argument("--face", required=True, help="face name (default | terminus | plexmono | ...)")
    ap.add_argument("--out", required=True, help="output font_data_<face>.c")
    ap.add_argument("--keep-default", default="",
                    help="extra code points to keep as BF default (e.g. '0x21,0x40')")
    ap.add_argument("--outline-mode", choices=["exterior", "full"], default="full",
                    help="outline mode for hand-authored overrides (must match the face)")
    args = ap.parse_args()

    base = parse_base(Path(args.base))
    cand = Path(args.candidate).read_bytes()
    if len(cand) != COUNT * STRIDE:
        sys.exit(f"error: candidate {args.candidate} is {len(cand)} bytes, expected {COUNT*STRIDE}")

    extra_keep = parse_codes(args.keep_default)
    overlay = overlay_set(extra_keep)
    overrides = load_text_overrides(args.face)

    n_overlay = n_keep = n_override = 0
    for code in range(COUNT):
        if code in overrides:
            base[code * STRIDE:(code + 1) * STRIDE] = override_to_bytes(overrides[code])
            n_override += 1
        elif code in overlay:
            base[code * STRIDE:(code + 1) * STRIDE] = cand[code * STRIDE:(code + 1) * STRIDE]
            n_overlay += 1
        else:
            n_keep += 1  # BF default retained (symbols / GLOBAL_KEEP / non-ASCII)

    write_c(Path(args.out), args.face, Path(args.base).name, Path(args.candidate).name, base)
    print(f"[{args.face}] overlaid={n_overlay} kept-BF={n_keep} hand-overrides={n_override} "
          f"-> {args.out} ({len(base)} bytes)")


if __name__ == "__main__":
    main()
